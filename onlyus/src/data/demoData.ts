export function makeSvgArt(title: string, c1: string, c2: string, emoji: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="720" height="540" viewBox="0 0 720 540">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${c1}"/>
        <stop offset="100%" stop-color="${c2}"/>
      </linearGradient>
      <radialGradient id="glow" cx="50%" cy="45%" r="55%">
        <stop offset="0%" stop-color="rgba(255,255,255,0.28)"/>
        <stop offset="100%" stop-color="rgba(0,0,0,0)"/>
      </radialGradient>
    </defs>
    <rect width="720" height="540" fill="#0b0614"/>
    <rect width="720" height="540" fill="url(#g)" opacity="0.48"/>
    <rect width="720" height="540" fill="url(#glow)"/>
    <circle cx="150" cy="120" r="64" fill="#ff4d8d" opacity="0.18"/>
    <circle cx="590" cy="410" r="95" fill="#8b5cf6" opacity="0.22"/>
    <text x="360" y="255" font-size="92" text-anchor="middle" dominant-baseline="middle">${emoji}</text>
    <text x="360" y="365" font-family="system-ui,-apple-system,sans-serif" font-size="28" font-weight="600" fill="#ffffff" text-anchor="middle" opacity="0.92">${title}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

